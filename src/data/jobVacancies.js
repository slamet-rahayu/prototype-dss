export const JOB_WORK_MODELS = ["Semua", "Hybrid", "Remote", "On-site"];
export const JOB_WORK_TYPES = ["Semua", "Full-time", "Magang", "Kontrak"];
export const JOB_EXPERIENCE_LEVELS = ["Semua", "Fresh Graduate / 0-2 Tahun", "1-3 Tahun", "Fresh Graduate / Entry-level"];

/**
 * Filter and query job vacancies in-memory
 */
export function queryJobVacancies({
  career,
  search,
  workModel,
  workType,
  experienceLevel
} = {}) {
  return JOB_VACANCIES.filter(job => {
    if (career && career !== "Semua") {
      const target = career.toLowerCase().trim();
      const matchCareer = job.careerName.toLowerCase().trim() === target ||
        job.careerName.toLowerCase().includes(target) ||
        target.includes(job.careerName.toLowerCase());
      if (!matchCareer) return false;
    }

    if (workModel && workModel !== "Semua") {
      if (job.workModel.toLowerCase() !== workModel.toLowerCase()) return false;
    }

    if (workType && workType !== "Semua") {
      if (!job.workType.toLowerCase().includes(workType.toLowerCase())) return false;
    }

    if (experienceLevel && experienceLevel !== "Semua") {
      if (!job.experienceLevel.toLowerCase().includes(experienceLevel.toLowerCase())) return false;
    }

    if (search && search.trim() !== "") {
      const q = search.toLowerCase().trim();
      const match =
        job.title.toLowerCase().includes(q) ||
        job.company.toLowerCase().includes(q) ||
        job.location.toLowerCase().includes(q) ||
        job.careerName.toLowerCase().includes(q) ||
        (job.requirements || []).some(r => r.toLowerCase().includes(q)) ||
        (job.skills || []).some(s => s.toLowerCase().includes(q));
      if (!match) return false;
    }

    return true;
  });
}
